const ARROW_COLORS_EN = [
  'red',
  'orange',
  'yellow',
  'green',
  'mint',
  'cyan',
  'blue',
  'indigo',
  'purple',
  'pink',
  'brown',
  'gray',
];

const ARROW_COLORS_ZH = ['红', '橙', '黄', '绿', '青', '蓝', '靛', '紫', '粉', '莓', '棕', '灰'];

export class I18n {
  static lang: Lang = 'en';

  static setLang(lang: Lang): void {
    I18n.lang = lang === 'zh' ? 'zh' : 'en';
  }

  static t(key: I18nKey, vars?: Record<string, string | number>): string {
    const dict = I18n.lang === 'zh' ? ZH_STRINGS : EN_STRINGS;
    let out: string = dict[key];
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        out = out.split(`{${k}}`).join(String(v));
      }
    }
    return out;
  }

  static arrowColorName(colorIdx: number): string {
    const list = I18n.lang === 'zh' ? ARROW_COLORS_ZH : ARROW_COLORS_EN;
    return list[colorIdx % list.length];
  }
}
