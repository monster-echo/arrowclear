/** 当前日期命中的节日（窗口含端点，跨年窗口支持）。 */
export function festivalForDate(now: Date): FestivalDef | null {
  const md = now.getMonth() + 1;
  const dd = now.getDate();
  const v = md * 100 + dd;
  for (const f of FESTIVAL_SHAPES) {
    const a = f.start[0] * 100 + f.start[1];
    const b = f.end[0] * 100 + f.end[1];
    if (a <= b ? v >= a && v <= b : v >= a || v <= b) return f;
  }
  return null;
}

/** 兼容旧引用：全部图案的合集。 */
/** 500 关图案关需要足够箭量：主图案剪影整体放大 1.35×（面积 ×1.8）。 */
const SHAPE_SCALE_BOOST = 1.35;
for (const def of [...MAJOR_SHAPES, ...MINOR_SHAPES]) {
  if (def.scaleX === undefined) def.scaleX = 2;
  if (def.scaleY === undefined) def.scaleY = 2;
  def.scaleX *= SHAPE_SCALE_BOOST;
  def.scaleY *= SHAPE_SCALE_BOOST;
}

export const SHAPES: ShapeDef[] = [...MAJOR_SHAPES];

const cache = new Map<string, ShapeMask>();

function normalize(rows: string[]): string[] {
  const width = Math.max(...rows.map((r) => r.length));
  return rows.map((r) => r.padEnd(width, '.'));
}

/** Compile an ASCII silhouette into a flat 0/1 mask. */
export function compileShape(def: ShapeDef): ShapeMask {
  const hit = cache.get(def.id);
  if (hit) return hit;
  const src = normalize(def.rows);
  const sx = Math.max(1, def.scaleX ?? 2);
  const sy = Math.max(1, def.scaleY ?? 2);
  const baseW = src[0].length;
  const baseH = src.length;
  const cols = Math.max(1, Math.round(baseW * sx));
  const rows = Math.max(1, Math.round(baseH * sy));
  const mask = new Uint8Array(cols * rows);
  let area = 0;
  for (let y = 0; y < rows; y++) {
    const by = Math.min(baseH - 1, Math.floor((y + 0.5) / sy));
    for (let x = 0; x < cols; x++) {
      const bx = Math.min(baseW - 1, Math.floor((x + 0.5) / sx));
      if (src[by][bx] !== '#') continue;
      mask[y * cols + x] = 1;
      area++;
    }
  }
  const compiled: ShapeMask = { id: def.id, name: def.name, cols, rows, mask, area };
  cache.set(def.id, compiled);
  return compiled;
}

/**
 * 主图案：每 10 关一幅（id % 10 === 0）。50 幅循环使用（第 51 幅起重头再来，
 * 服务每周滚动新关）。
 */
export function majorShapeForLevel(id: number): ShapeMask {
  const idx = Math.floor(id / 10) - 1;
  const safe = ((idx % MAJOR_SHAPES.length) + MAJOR_SHAPES.length) % MAJOR_SHAPES.length;
  return compileShape(MAJOR_SHAPES[safe]);
}

/** 小歇图案：每章 L7，从符号池按章轮换。 */
export function minorShapeForLevel(id: number): ShapeMask {
  const chapter = Math.max(1, Math.floor((id - 1) / 20) + 1);
  const idx = (chapter - 1) % MINOR_SHAPES.length;
  return compileShape(MINOR_SHAPES[idx]);
}

/**
 * 面积自适应编译：把图案等比缩放到 [minArea, maxArea] 目标区间
 * （对应 90~180 支箭 ≈ 3~5 分钟游玩量）。缩放系数进缓存键。
 */
export function compileShapeScaled(def: ShapeDef, minArea: number, maxArea: number): ShapeMask {
  const base = compileShape(def);
  if (base.area >= minArea && base.area <= maxArea) return base;
  const k = Math.sqrt(base.area < minArea ? minArea / base.area : maxArea / base.area);
  return compileShape({
    id: `${def.id}@${k.toFixed(3)}`,
    name: def.name,
    rows: def.rows,
    scaleX: (def.scaleX ?? 2) * k,
    scaleY: (def.scaleY ?? 2) * k,
  });
}

/**
 * 程序化盘面变异（普通关专用）：满盘 → 圆角 / 八边形大切 / 内洞 / 边缺口 /
 * 中心甜甜圈洞，按世界等级递增强度。同 seed 确定；保证最大连通域 ≥92%
 * 面积（生成器才能填满），洞避开 Boss 中心区。
 */
export function proceduralBoardMask(
  seed: number,
  cols: number,
  rows: number,
  tier: number,
): { mask: Uint8Array; name: string } {
  const rng = new Rng(seed ^ 0x9e3779b9);
  const mk = (): Uint8Array<ArrayBuffer> => {
    const m = new Uint8Array(cols * rows).fill(1);
    const set = (x: number, y: number, v: number): void => {
      if (x >= 0 && y >= 0 && x < cols && y < rows) m[y * cols + x] = v;
    };
    const ops: string[] = [];

    // 圆角 / 八边形大切。
    const cornerR = tier >= 3 ? 4 + rng.int(4) : 2 + rng.int(2);
    for (let y = 0; y < cornerR; y++) {
      for (let x = 0; x < cornerR; x++) {
        if ((x - cornerR + 0.5) ** 2 + (y - cornerR + 0.5) ** 2 > cornerR * cornerR) {
          set(x, y, 0);
          set(cols - 1 - x, y, 0);
          set(x, rows - 1 - y, 0);
          set(cols - 1 - x, rows - 1 - y, 0);
        }
      }
    }
    ops.push(tier >= 3 ? '八边形' : '圆角');

    // 内洞（避开中心 Boss 区与边缘）。
    const holes = 1 + rng.int(tier);
    for (let h = 0; h < holes; h++) {
      const r = 2 + rng.int(2);
      for (let tries = 0; tries < 8; tries++) {
        const cx = r + 3 + rng.int(Math.max(1, cols - 2 * (r + 3)));
        const cy = r + 3 + rng.int(Math.max(1, rows - 2 * (r + 3)));
        const inBossZone =
          cx > cols * 0.28 && cx < cols * 0.72 && cy > rows * 0.3 && cy < rows * 0.66;
        if (inBossZone) continue;
        let clear = true;
        for (let y = cy - r - 2; y <= cy + r + 2 && clear; y++) {
          for (let x = cx - r - 2; x <= cx + r + 2 && clear; x++) {
            if (x >= 0 && y >= 0 && x < cols && y < rows && m[y * cols + x] === 0) clear = false;
          }
        }
        if (!clear) continue;
        for (let y = cy - r; y <= cy + r; y++) {
          for (let x = cx - r; x <= cx + r; x++) {
            if ((x - cx) ** 2 + (y - cy) ** 2 <= r * r) set(x, y, 0);
          }
        }
        ops.push('内洞');
        break;
      }
    }

    // 边缺口（浅半圆，不伤连通）。
    if (tier >= 2) {
      const nicks = 1 + rng.int(2);
      for (let n = 0; n < nicks; n++) {
        const r = 2 + rng.int(2);
        const side = rng.int(4);
        const c = r + 2 + rng.int(Math.max(1, (side < 2 ? cols : rows) - 2 * (r + 2)));
        for (let d = -r; d <= r; d++) {
          for (let deep = 0; deep <= r; deep++) {
            if (d * d + deep * deep > r * r) continue;
            if (side === 0) set(c + d, deep, 0);
            else if (side === 1) set(c + d, rows - 1 - deep, 0);
            else if (side === 2) set(deep, c + d, 0);
            else set(cols - 1 - deep, c + d, 0);
          }
        }
      }
      ops.push('边缺口');
    }

    // 中心甜甜圈（W4+ 偶发）。
    if (tier >= 3 && rng.next() < 0.35) {
      const r = Math.floor(Math.min(cols, rows) * 0.16);
      const cx = Math.floor(cols / 2);
      const cy = Math.floor(rows * 0.22);
      for (let y = cy - r; y <= cy + r; y++) {
        for (let x = cx - r; x <= cx + r; x++) {
          if ((x - cx) ** 2 + (y - cy) ** 2 <= r * r) set(x, y, 0);
        }
      }
      ops.push('天窗');
    }
    return m;
  };

  // 生成 3 个候选，取最大连通域占比最高者。
  const flood = (m: Uint8Array<ArrayBuffer>): number => {
    const seen = new Uint8Array(cols * rows);
    let best = 0;
    const stack: number[] = [];
    for (let i = 0; i < m.length; i++) {
      if (!m[i] || seen[i]) continue;
      let size = 0;
      stack.push(i);
      seen[i] = 1;
      while (stack.length) {
        const j = stack.pop()!;
        size++;
        const x = j % cols;
        const y = Math.floor(j / cols);
        for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1]] as const) {
          const nx = x + dx;
          const ny = y + dy;
          if (nx < 0 || ny < 0 || nx >= cols || ny >= rows) continue;
          const k = ny * cols + nx;
          if (m[k] && !seen[k]) {
            seen[k] = 1;
            stack.push(k);
          }
        }
      }
      best = Math.max(best, size);
    }
    const total = m.reduce((a, b) => a + b, 0);
    return total ? best / total : 0;
  };

  let bestMask: Uint8Array<ArrayBuffer> = new Uint8Array(cols * rows).fill(1);
  let bestRatio = 0;
  for (let c = 0; c < 3; c++) {
    const m = mk();
    const ratio = flood(m);
    if (ratio > bestRatio) {
      bestRatio = ratio;
      bestMask = m;
    }
    if (ratio >= 0.995) break;
  }
  if (bestRatio < 0.92) bestMask = new Uint8Array(cols * rows).fill(1); // 兜底满盘
  const area = bestMask.reduce((a, b) => a + b, 0);
  void area;
  return { mask: bestMask, name: '异形盘' };
}

/** Cycle the shape library; each level gets a different silhouette. */
export function shapeForLevel(id: number): ShapeMask {
  const index = ((Math.max(1, Math.floor(id)) - 1) % SHAPES.length + SHAPES.length) % SHAPES.length;
  return compileShape(SHAPES[index]);
}

export function shapeForId(id: string): ShapeMask | undefined {
  const def = MAJOR_SHAPES.find((s) => s.id === id) ?? MINOR_SHAPES.find((s) => s.id === id);
  return def ? compileShape(def) : undefined;
}
