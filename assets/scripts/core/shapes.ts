/**
 * Silhouette masks for "picture levels".
 *
 * A shape is a small ASCII picture: `#` means an arrow body may occupy the
 * cell, `.` means the cell is outside the picture. The playable grid is always
 * the shape's bounding box, so arrows can leave through the silhouette edge
 * (and through holes such as a cup handle) without any special case in the
 * rule engine.
 *
 * Keep the art blocky on purpose: at 3–4 px strokes the silhouette is read
 * from the *negative space* around the arrows, not from an outline.
 *
 * 500 关结构（规则书 §6）：主图案 50 幅，每 10 关一幅（id % 10 === 0），
 * 批次顺序 = 通用符号 → 生活图鉴 → 名画灵感·几何再创作 → 世界地标 → 华彩终章。
 * 全部原创块状剪影，零版权风险；名画批次是对公有领域大师作品的几何致敬，
 * 不描摹原图。小歇图案（每章 L7）从 10 个简单符号里轮换。
 */

import { Rng } from './rng';

export interface ShapeDef {
  id: string;
  name: string;
  rows: string[];
  /** Upscale the blocky ASCII art so the picture has more arrow-sized cells. */
  scaleX?: number;
  scaleY?: number;
}

export interface ShapeMask {
  id: string;
  name: string;
  cols: number;
  rows: number;
  mask: Uint8Array;
  area: number;
}

