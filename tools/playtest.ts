/**
 * 自动化试玩评分与时间校准脚本：
 *   npm run playtest          — 试玩全部 500 关 + Boss 小关 + 501 彩蛋关，生成评分与推荐时间报告
 *   npm run playtest:apply    — 试玩后把校准时间写回 assets/scripts/core/levelTimes.ts
 *   node .tmp/playtest.mjs --levels=1,19,21,50,119,452  — 只试玩指定关卡并打印明细
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { BONUS_CHALLENGE_ID, LEVEL_COUNT, getLevel, getLevelParts, isBoss, worldOf } from '../assets/scripts/core/levels';
import { PlaytestReport, playtestLevel } from '../assets/scripts/core/playtest';

const args = process.argv.slice(2);
const apply = args.includes('--apply');
const levelsArg = args.find((a) => a.startsWith('--levels='));
const selectedIds = levelsArg
  ? levelsArg
      .slice('--levels='.length)
      .split(',')
      .map((s) => Number(s.trim()))
      .filter((n) => Number.isFinite(n) && n >= 1)
  : null;

const ids: number[] = selectedIds ?? [
  ...Array.from({ length: LEVEL_COUNT }, (_, i) => i + 1),
  BONUS_CHALLENGE_ID,
];

const reports: PlaytestReport[] = [];
const t0 = Date.now();

for (const id of ids) {
  if (id <= LEVEL_COUNT && isBoss(id) && worldOf(id) >= 2) {
    for (const part of getLevelParts(id)) {
      reports.push(playtestLevel(part));
    }
  } else {
    reports.push(playtestLevel(getLevel(id)));
  }
}

const labelOf = (r: PlaytestReport): string => (r.part ? `${r.id}(${r.part}/3)` : String(r.id));

if (selectedIds) {
  console.log('关       形态       模式    箭数    Boss  开局自由  T20/T50/T80     误触  连消  评分(级)  现限时->建议');
  for (const r of reports) {
    const tStr = `${r.clearTimeFast}/${r.clearTimeMedian}/${r.clearTimeCareful}s`;
    console.log(
      [
        labelOf(r).padEnd(8),
        r.shape.slice(0, 10).padEnd(10),
        r.mode.padEnd(7),
        String(r.arrows).padStart(4),
        (r.hasBoss ? 'Y' : '-').padStart(5),
        String(r.openingFree).padStart(8),
        tStr.padStart(14),
        String(r.avgMistakes).padStart(5),
        String(r.maxCascadeBurst).padStart(4),
        `${r.score}(${r.tier})`.padStart(8),
        `${r.currentTimeLimit}s->${r.recommendedTime}s`.padStart(12),
      ].join(' '),
    );
  }
  console.log(`\n试玩 ${reports.length} 个盘面，耗时 ${Date.now() - t0}ms`);
  process.exit(0);
}

if (apply) {
  const levelMap: Record<number, number> = {};
  const bossMap: Record<string, number> = {};
  for (const r of reports) {
    if (r.part) {
      bossMap[`${r.id}:${r.part}`] = r.recommendedTime;
    } else if (r.mode !== 'zen' && r.id <= LEVEL_COUNT) {
      levelMap[r.id] = r.recommendedTime;
    }
    // 写入校准值后更新报告中的现限时与 timeFit/总分，便于报告反映真实上线结果。
    if (r.mode !== 'zen' && r.id <= LEVEL_COUNT) {
      const oldFit = r.subScores.timeFit;
      r.currentTimeLimit = r.recommendedTime;
      r.subScores.timeFit = 10;
      r.score = Math.min(100, r.score - oldFit + 10);
      r.tier = r.score >= 85 ? 'S' : r.score >= 75 ? 'A' : r.score >= 62 ? 'B' : 'C';
    }
  }

  const tsOut = `/**
 * Playtest-calibrated time limits generated by \`tools/playtest.ts --apply\`.
 * Generated at ${new Date().toISOString()} (${reports.length} boards).
 */
export const LEVEL_TIME_OVERRIDES: Record<number, number> = ${JSON.stringify(levelMap, null, 2)};

export const BOSS_PART_TIME_OVERRIDES: Record<string, number> = ${JSON.stringify(bossMap, null, 2)};
`;
  writeFileSync('assets/scripts/core/levelTimes.ts', tsOut);
  console.log(`✔ 已写入时间校准表 assets/scripts/core/levelTimes.ts（${Object.keys(levelMap).length} 主线关 + ${Object.keys(bossMap).length} Boss 小关）`);
}

// 汇总统计与 Markdown 报告输出
const avg = (xs: number[]): number => (xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : 0);
const tiers = { S: 0, A: 0, B: 0, C: 0 };
for (const r of reports) tiers[r.tier]++;

const worldRows: string[] = [];
for (let w = 1; w <= 5; w++) {
  const from = (w - 1) * 100 + 1;
  const to = w * 100;
  const list = reports.filter((r) => r.id >= from && r.id <= to);
  const nonZen = list.filter((r) => r.mode !== 'zen');
  worldRows.push(
    `| 世界 ${w} (${from}-${to}) | ${list.length} | ${avg(list.map((r) => r.arrows)).toFixed(0)} | ${avg(list.map((r) => r.clearTimeMedian)).toFixed(0)}s | ${avg(list.map((r) => r.clearTimeCareful)).toFixed(0)}s | ${avg(nonZen.map((r) => r.recommendedTime)).toFixed(0)}s | ${avg(list.map((r) => r.maxCascadeBurst)).toFixed(1)} | ${avg(list.map((r) => r.score)).toFixed(1)} |`,
  );
}

const lowest15 = [...reports].sort((a, b) => a.score - b.score).slice(0, 15);
const highest10 = [...reports].sort((a, b) => b.score - a.score).slice(0, 10);

const md = `# 13 · 全关卡模拟试玩评分与时间校准报告

> 由 \`tools/playtest.ts\`（人类认知模拟试玩引擎）对 **${reports.length}** 个盘面逐箭实玩生成，耗时 ${((Date.now() - t0) / 1000).toFixed(1)}s。
> 评分五维（0~100）：突破紧张感(25) + 锁与连锁爽感(30) + 节奏波浪(20) + 公平容错(15) + 时限匹配(10)。
>
> - **等级分布**：**S ${tiers.S}** · **A ${tiers.A}** · **B ${tiers.B}** · **C ${tiers.C}**
> - **平均试玩评分**：**${avg(reports.map((r) => r.score)).toFixed(1)}**
> - **平均中位通关时长 (T50)**：**${avg(reports.map((r) => r.clearTimeMedian)).toFixed(0)}s** ｜ **80 分位通关时长 (T80)**：**${avg(reports.map((r) => r.clearTimeCareful)).toFixed(0)}s**
> - **平均最大连消爆发**：**${avg(reports.map((r) => r.maxCascadeBurst)).toFixed(1)} 支** ｜ **平均模拟误触**：**${avg(reports.map((r) => r.avgMistakes)).toFixed(2)} 次**

## 分世界试玩统计

| 区间 | 盘面数 | 平均箭数 | 试玩 T50 | 试玩 T80 | 校准限时(非禅意) | 平均最大连消 | 平均试玩分 |
| --- | --- | --- | --- | --- | --- | --- | --- | --- |
${worldRows.join('\n')}

## 试玩高分代表关（Top 10）

| 关 | 模式 | 形态 | 箭数 | Boss | T50 / T80 | 校准限时 | 最大连消 | 试玩分 |
| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |
${highest10
  .map(
    (r) =>
      `| ${labelOf(r)} | ${r.mode} | ${r.shape} | ${r.arrows} | ${r.hasBoss ? '是' : '否'} | ${r.clearTimeMedian}s / ${r.clearTimeCareful}s | ${r.recommendedTime === 0 ? '∞' : `${r.recommendedTime}s`} | ${r.maxCascadeBurst} | **${r.score}** (${r.tier}) |`,
  )
  .join('\n')}

## 试玩低分待观察关（Bottom 15）

| 关 | 模式 | 形态 | 箭数 | 开局自由 | T50 / T80 | 校准限时 | 拆项(紧/连/节/公/时) | 试玩分 |
| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |
${lowest15
  .map(
    (r) =>
      `| ${labelOf(r)} | ${r.mode} | ${r.shape} | ${r.arrows} | ${r.openingFree} | ${r.clearTimeMedian}s / ${r.clearTimeCareful}s | ${r.recommendedTime === 0 ? '∞' : `${r.recommendedTime}s`} | ${r.subScores.tension}/${r.subScores.cascade}/${r.subScores.pacing}/${r.subScores.fairness}/${r.subScores.timeFit} | ${r.score} (${r.tier}) |`,
  )
  .join('\n')}

## 全量试玩明细

| 关 | 模式 | 形态 | 箭数 | Boss | 开局自由 | T20 / T50 / T80 | 误触 | 最大连消 | 校准限时 | 试玩分 |
| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |
${reports
  .map(
    (r) =>
      `| ${labelOf(r)} | ${r.mode} | ${r.shape} | ${r.arrows} | ${r.hasBoss ? '✓' : '-'} | ${r.openingFree} | ${r.clearTimeFast}/${r.clearTimeMedian}/${r.clearTimeCareful}s | ${r.avgMistakes} | ${r.maxCascadeBurst} | ${r.recommendedTime === 0 ? '∞' : `${r.recommendedTime}s`} | ${r.score} (${r.tier}) |`,
  )
  .join('\n')}
`;

writeFileSync('docs/13-试玩评分与时间校准报告.md', md);
mkdirSync('.tmp', { recursive: true });
writeFileSync('.tmp/playtest-report.json', JSON.stringify(reports, null, 2));

console.log(
  `试玩完成 ${reports.length} 盘面 (${((Date.now() - t0) / 1000).toFixed(1)}s) | S ${tiers.S} / A ${tiers.A} / B ${tiers.B} / C ${tiers.C} | 均分 ${avg(reports.map((r) => r.score)).toFixed(1)} | 报告: docs/13-试玩评分与时间校准报告.md`,
);
